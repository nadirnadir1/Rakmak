results = []
for s, e, cands in SEGS:
    t0 = time.time()
    a = audio[int(max(0, s - 0.05) * sr): int(min(len(audio) / sr, e + 0.05) * sr)]
    a = np.concatenate([np.zeros(int(0.3 * sr), np.float32), a, np.zeros(int(0.8 * sr), np.float32)])
    cross = W.encode(a)
    g = greedy(cross)
    scored = sorted(((W.score(cross, c)[0], c) for c in dict.fromkeys(cands)), reverse=True)
    print(f"\n[{s:.2f}-{e:.2f}] greedy: {g}   ({time.time()-t0:.1f}s)", flush=True)
    for sc, c in scored[:5]:
        print(f"   {sc:8.2f}  {c}", flush=True)
    results.append({"start": s, "end": e, "greedy": g, "best": scored[0][1], "ranked": scored[:5]})
json.dump(results, open(out_path, "w"), ensure_ascii=False, indent=1)
