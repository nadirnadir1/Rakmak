"""Pick the best transcript per voiceover segment by Whisper forced-decoding log-prob,
and print a greedy decode (with generous padding) for reference."""
import itertools, json, sys, time
import numpy as np
import soundfile as sf
sys.path.insert(0, sys.argv[1])
from whisper_align import Whisper

model_dir, wav, out_path = sys.argv[2:5]
audio, sr = sf.read(wav, dtype="float32")
W = Whisper(model_dir)

def greedy(cross, max_len=120):
    pre = W.prefix("ar", timestamps=False)
    k, v = cross
    ck = np.zeros((W.n_layer, 1, W.n_ctx, W.n_state), np.float32)
    cv = ck.copy()
    toks = list(pre); out = []
    feed = list(pre); off = 0
    for _ in range(max_len):
        lg, ck, cv = W.dec.run(None, {"tokens": np.array([feed], np.int64), "in_n_layer_self_k_cache": ck,
            "in_n_layer_self_v_cache": cv, "n_layer_cross_k": k, "n_layer_cross_v": v,
            "offset": np.array([off], np.int64)})
        off += len(feed)
        nxt = int(np.argmax(lg[0, -1, :W.ts0]))
        if nxt == W.eot: break
        out.append(nxt); feed = [nxt]
    return W.tok.decode([t for t in out if t < W.eot])

